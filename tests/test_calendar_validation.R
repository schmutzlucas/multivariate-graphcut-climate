source("R/load.R");load_mvgc();source("R/preprocessing/cf_calendar_validation.R")
x<-audit_cf_dates(0:359+.5,"days since 2000-01-01 00:00:00","360_day")
key<-sprintf("%04d-%02d-%02d",x$year,x$month,x$day)
stopifnot(length(unique(key))==360L,all(x$year==2000),sum(x$day==31)==0,
          "2000-02-30"%in%key,key[360]=="2000-12-30")
x<-audit_cf_dates(c(0,1,2)*24,"hours since 2000-02-28 00:00:00","365_day")
stopifnot(identical(x$day,c(28L,1L,2L)),identical(x$month,c(2L,3L,3L)))
x<-audit_cf_dates(0:2,"days since 2000-02-28","366_day")
stopifnot(identical(x$day,c(28L,29L,1L)))
x<-audit_cf_dates(c(-1,0,1),"days since 2000-01-01","360_day")
stopifnot(identical(x$year,c(1999L,2000L,2000L)),identical(x$day,c(30L,1L,2L)))
x<-audit_cf_dates(0:2,"days since 2000-02-28 12:00:00","standard")
stopifnot(identical(x$day,c(28L,29L,1L)))
cat("PASS: native 360/365/366/Gregorian audit calendars, leap dates and negative offsets.\n")
